func Test_calc_doom(t *testing.T) {

	stegol.CheckIntegerEqual(t, 0, calc_doom(0))

	cases := []struct {
		from, to, step uint64
		want           uint32
	}{
		{1, 10, 1, 1},
		{10, 100, 1, 2},
		{100, 1_000, 1, 3},
		{1_000, 10_000, 1, 4},
		{10_000, 100_000, 1, 5},
		{100_000, 1_000_000, 1, 6},
		{1_000_000, 10_000_000, 1_000_000, 7},
		{10_000_000, 100_000_000, 10_000_000, 8},
		{100_000_000, 1_000_000_000, 100_000_000, 9},
		{1_000_000_000, 10_000_000_000, 1_000_000_000, 10},
		{10_000_000_000, 100_000_000_000, 10_000_000_000, 11},
		{100_000_000_000, 1_000_000_000_000, 100_000_000_000, 12},
		{1_000_000_000_000, 10_000_000_000_000, 1_000_000_000_000, 13},
		{10_000_000_000_000, 100_000_000_000_000, 10_000_000_000_000, 14},
		{100_000_000_000_000, 1_000_000_000_000_000, 100_000_000_000_000, 15},
		{1_000_000_000_000_000, 10_000_000_000_000_000, 1_000_000_000_000_000, 16},
		{10_000_000_000_000_000, 100_000_000_000_000_000, 10_000_000_000_000_000, 17},
		{100_000_000_000_000_000, 1_000_000_000_000_000_000, 100_000_000_000_000_000, 18},
		{1_000_000_000_000_000_000, 10_000_000_000_000_000_000, 1_000_000_000_000_000_000, 19},
		{10_000_000_000_000_000_000, 18_000_000_000_000_000_000, 1_000_000_000_000_000_000, 20},
	}

	for _, tc := range cases {
		for i := tc.from; i != tc.to; i += tc.step {
			stegol.CheckIntegerEqual(t, tc.want, calc_doom(i))
		}
	}
}

